#!/usr/bin/env python3
"""Independent (Python stdlib) implementation of the Pol key schedule and SAS.

Writes protocol/vectors.json. The Kotlin core and the Swift client are tested against these values, so the three
implementations are checked against each other. Uses only hashlib/hmac; no network access.
"""
import hashlib, hmac, json, pathlib

def hkdf(ikm, salt, info, length):
    prk = hmac.new(salt or bytes(32), ikm, hashlib.sha256).digest()
    out, t, i = b"", b"", 1
    while len(out) < length:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        out += t; i += 1
    return out[:length]

def sas(transcript):
    h = hashlib.sha256(b"POL1-sas" + transcript).digest()
    return "%06d" % (int.from_bytes(h[:4], "big") % 1_000_000)

transcript = bytes(range(32))
shared = bytes([7] * 32)
okm = hkdf(shared, transcript, b"POL1 keys", 64)
ident = bytes([4]) + bytes(range(64))
vectors = {
    "description": "Pol link protocol v1 test vectors (generated by tools/vectors.py)",
    "sas": {"transcript": transcript.hex(), "sas": sas(transcript)},
    "keys": {"shared": shared.hex(), "transcript": transcript.hex(), "info": "POL1 keys",
             "client_to_gateway": okm[:32].hex(), "gateway_to_client": okm[32:].hex()},
    "device_id": {"public_key": ident.hex(), "id": hashlib.sha256(ident).digest()[:16].hex()},
    "record": {"type": 16, "body": "aabb", "encoded": "000310aabb"},
    "nonce": {"counter": 5, "nonce": (bytes(4) + (5).to_bytes(8, "big")).hex(), "aad": (bytes([0x10]) + (5).to_bytes(8, "big")).hex()},
}
def ulaw(sample):
    # Classic CCITT/Sun g711.c linear2ulaw (bias 0x84, clip 32635), written independently of the app code.
    sign = 0x80 if sample < 0 else 0
    mag = min(-sample if sample < 0 else sample, 32635) + 0x84
    seg = 0
    for i, top in enumerate([0xFF, 0x1FF, 0x3FF, 0x7FF, 0xFFF, 0x1FFF, 0x3FFF, 0x7FFF]):
        if mag <= top:
            seg = i; break
    return (~(sign | (seg << 4) | ((mag >> (seg + 3)) & 0x0F))) & 0xFF

samples = [-32768, -20000, -1000, -100, -1, 0, 1, 100, 1000, 8159, 20000, 32767]
vectors["g711"] = {"samples": samples, "ulaw": [ulaw(v) for v in samples]}

p = pathlib.Path(__file__).resolve().parent.parent / "protocol" / "vectors.json"
p.write_text(json.dumps(vectors, indent=2) + "\n")
print(json.dumps(vectors, indent=2))
